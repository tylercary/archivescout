/**
 * Realistic mock listing catalogue used by the MockMarketplaceProvider and as
 * a fallback for live providers without credentials.
 *
 * Imagery uses seeded picsum.photos URLs — safe, deterministic placeholders
 * with no marketplace ToS implications. Swap for real CDN images once a
 * licensed API integration is in place (see docs/INTEGRATION.md).
 *
 * `listedAt` values are anchored around 2026-07-29 so "time since listed" and
 * "newly listed" filters behave predictably in the demo.
 */

function img(seed: string, count = 2): string[] {
  return Array.from(
    { length: count },
    (_, i) => `https://picsum.photos/seed/${seed}-${i}/900/1100`,
  );
}

