export const MOCK_LISTINGS: Listing[] = RAW.map((raw) => {
  const { imageSeed, imageCount, currency, ...rest } = raw;
  return {
    ...rest,
    id: `${raw.marketplace}:${raw.externalId}`,
    currency: currency ?? "USD",
    imageUrls: img(imageSeed, imageCount ?? 2),
  };
});

export function mockListingsFor(marketplace: Marketplace): Listing[] {
  return MOCK_LISTINGS.filter((l) => l.marketplace === marketplace);
}
